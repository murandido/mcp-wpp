package main

import (
	"flag"
	"fmt"
	"os"
	"strings"
	"text/tabwriter"

	mcpsrv "github.com/murandido/mcp-wpp/internal/mcp"
)

func runTools(args []string) int {
	fs := flag.NewFlagSet("tools", flag.ContinueOnError)
	fs.SetOutput(os.Stderr)
	md := fs.Bool("markdown", false, "print a Markdown reference (used by `make docs`)")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	cat := mcpsrv.Catalog()
	yes := func(b bool) string {
		if b {
			return "yes"
		}
		return ""
	}
	if !*md {
		tw := tabwriter.NewWriter(os.Stdout, 0, 0, 2, ' ', 0)
		fmt.Fprintln(tw, "TOOL\tGROUP\tDEFAULT\tREAD-ONLY\tNEEDS APPROVAL")
		for _, t := range cat {
			fmt.Fprintf(tw, "%s\t%s\t%s\t%s\t%s\n", t.Name, t.Group, yes(t.Default), yes(t.ReadOnly), yes(t.Confirm && !t.ReadOnly))
		}
		tw.Flush()
		return 0
	}
	fmt.Println("<!-- Generated by `make docs` from the tool registry. Do not edit by hand. -->")
	fmt.Println("# Tool reference")
	fmt.Println()
	fmt.Println("- **Default**: exposed without `-tools`. Opt-in groups are enabled with `-tools default,groups` (or `all`).")
	fmt.Println("- **Read-only**: available without `-write`.")
	fmt.Println("- **Approval**: with `-write`, the call follows the target chat's send policy (`wpp-mcp access send`): `confirm` (the default unless `-confirm-sends=false`) makes it a proposal you approve with `wpp-mcp outbox`, `direct` acts at once, `none` refuses it. Tools without a chat use the default.")
	fmt.Println("- **Chat access**: which chats the tool can reach under the access policy.")
	group := ""
	for _, t := range cat {
		if t.Group != group {
			group = t.Group
			fmt.Printf("\n## %s\n\n", group)
			fmt.Println("| Tool | Default | Read-only | Approval | Chat access | Description |")
			fmt.Println("|---|:-:|:-:|:-:|---|---|")
		}
		fmt.Printf("| `%s` | %s | %s | %s | %s | %s |\n", t.Name, yes(t.Default), yes(t.ReadOnly), yes(t.Confirm && !t.ReadOnly), t.Access, strings.ReplaceAll(t.Summary, "|", "\\|"))
	}
	return 0
}
